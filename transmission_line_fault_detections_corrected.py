# Initialize the models dictionary if it doesn't exist
if 'models' not in locals() and 'models' not in globals():
    models = {}

# --- Data Preprocessing for this cell ---
# Ensure X_columns and target are defined (they are in the kernel state)
# Separate features (X_data) and target (y_data) from the 'dataset' DataFrame
X_data = dataset[X_columns] # Use a different name to avoid confusion with X_train/X_test
