import numpy as np
import pandas as pd

from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
from sklearn.ensemble import VotingClassifier
from sklearn.svm import SVC
from sklearn.linear_model import LogisticRegression
from xgboost import XGBClassifier
from catboost import CatBoostClassifier

# Define Base Models
xgb = XGBClassifier(
    n_estimators=300,
    learning_rate=0.05,
    max_depth=6,
    eval_metric='mlogloss',
    random_state=42
)

cat = CatBoostClassifier(
    iterations=300,
    learning_rate=0.05,
    depth=6,
    verbose=0,
    random_state=42
)

svm = SVC(
    kernel='rbf',
    probability=True,
    C=10,
    gamma='scale',
    random_state=42
)

# Hybrid Voting Classifier
hybrid_model = VotingClassifier(
    estimators=[
        ('xgb', xgb),
        ('cat', cat),
        ('svm', svm)
    ],
    voting='soft',
    weights=[3,3,1]
)

# 5-Fold Cross Validation
skf = StratifiedKFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

accuracy = []
precision = []
recall = []
f1 = []

print("5-Fold Cross Validation Results\n")

fold = 1

for train_index, test_index in skf.split(X_scaled, y_encoded):

    X_train, X_test = X_scaled[train_index], X_scaled[test_index]
    y_train, y_test = y_encoded[train_index], y_encoded[test_index]

    hybrid_model.fit(X_train, y_train)

    y_pred = hybrid_model.predict(X_test)

    acc = accuracy_score(y_test, y_pred)
    pre = precision_score(y_test, y_pred, average='weighted')
    rec = recall_score(y_test, y_pred, average='weighted')
    f = f1_score(y_test, y_pred, average='weighted')

    accuracy.append(acc)
    precision.append(pre)
    recall.append(rec)
    f1.append(f)

    print(f"Fold {fold}")
    print(f"Accuracy : {acc:.4f}")
    print(f"Precision: {pre:.4f}")
    print(f"Recall   : {rec:.4f}")
    print(f"F1 Score : {f:.4f}\n")

    fold += 1

# Summary Table
results = pd.DataFrame({
    "Fold":[1,2,3,4,5],
    "Accuracy":accuracy,
    "Precision":precision,
    "Recall":recall,
    "F1-Score":f1
})

print(results)

print("\nMean ± Standard Deviation\n")

print(f"Accuracy : {np.mean(accuracy):.4f} ± {np.std(accuracy):.4f}")
print(f"Precision: {np.mean(precision):.4f} ± {np.std(precision):.4f}")
print(f"Recall   : {np.mean(recall):.4f} ± {np.std(recall):.4f}")
print(f"F1 Score : {np.mean(f1):.4f} ± {np.std(f1):.4f}")

